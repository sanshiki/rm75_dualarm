"""TFDS builder for RM75 single-arm manipulation episodes.

The source files are raw ``episode.npy`` files generated by
``rlds/utils/npy_convert.py``. Each file contains one episode as a list of step
dicts.
"""

from __future__ import annotations

import glob
import importlib
import os
from pathlib import Path
import sys
from typing import Any, Dict, Iterable, Iterator, List, Optional, Tuple

import numpy as np
import tensorflow_datasets as tfds
from tqdm import tqdm


DATASET_DIR = Path(__file__).resolve().parent
ACTION_DIM = 7
STATE_DIM = 15
LANGUAGE_EMBEDDING_DIM = 512


def _install_numpy_core_aliases() -> None:
    """Allow NumPy 2.x object arrays to be unpickled with NumPy 1.x."""
    try:
        numpy_core = importlib.import_module("numpy.core")
    except ImportError:
        return

    sys.modules.setdefault("numpy._core", numpy_core)
    for name in (
        "multiarray",
        "numeric",
        "fromnumeric",
        "_multiarray_umath",
        "umath",
        "_internal",
    ):
        try:
            module = importlib.import_module(f"numpy.core.{name}")
        except ImportError:
            continue
        sys.modules.setdefault(f"numpy._core.{name}", module)


_install_numpy_core_aliases()


def _glob_patterns(env_name: str, default_pattern: Path) -> List[str]:
    value = os.environ.get(env_name)
    if not value:
        return [str(default_pattern)]
    return [item for item in value.split(os.pathsep) if item]


def _discover_episode_paths(split: str) -> List[str]:
    env_name = f"RM75_RLDS_{split.upper()}_GLOB"
    default_pattern = DATASET_DIR / "data" / split / "**" / "episode.npy"
    paths: List[str] = []
    for pattern in _glob_patterns(env_name, default_pattern):
        paths.extend(glob.glob(pattern, recursive=True))
    return sorted({str(Path(path)) for path in paths})


def _as_step_dict(step: Any) -> Dict[str, Any]:
    if isinstance(step, dict):
        return step
    if hasattr(step, "item"):
        value = step.item()
        if isinstance(value, dict):
            return value
    raise TypeError(f"expected step dict, got {type(step)!r}")


def _as_rgb_uint8(value: Any, key: str) -> np.ndarray:
    image = np.asarray(value)
    if image.ndim == 2:
        image = np.repeat(image[:, :, None], 3, axis=2)
    if image.ndim != 3 or image.shape[2] not in (3, 4):
        raise ValueError(f"{key} must have shape HxWx3 or HxWx4, got {image.shape}")
    image = image[:, :, :3]
    if image.dtype != np.uint8:
        image = np.clip(image, 0, 255).astype(np.uint8)
    return np.ascontiguousarray(image)


def _image_from_step(step: Dict[str, Any], keys: Iterable[str]) -> Optional[np.ndarray]:
    for key in keys:
        if key in step:
            return _as_rgb_uint8(step[key], key)
    return None


def _fixed_vector(step: Dict[str, Any], key: str, size: int, default: float = 0.0) -> np.ndarray:
    if key not in step or step[key] is None:
        return np.full(size, default, dtype=np.float32)
    value = np.asarray(step[key], dtype=np.float32).reshape(-1)
    if value.size == size:
        return value.astype(np.float32)
    if value.size > size:
        return value[:size].astype(np.float32)
    padded = np.full(size, default, dtype=np.float32)
    padded[: value.size] = value
    return padded


def _state_from_step(step: Dict[str, Any]) -> np.ndarray:
    ee_pose = _fixed_vector(step, "ee_pose", 7)
    gripper = np.asarray([float(step.get("gripper_cmd", 1.0))], dtype=np.float32)
    joint_state = _fixed_vector(step, "joint_state", 7)
    return np.concatenate([ee_pose, gripper, joint_state]).astype(np.float32)


def _action_from_step(step: Dict[str, Any], episode_path: str, index: int) -> np.ndarray:
    if "action" not in step:
        raise ValueError(f"{episode_path}: missing action in step {index}")
    action = np.asarray(step["action"], dtype=np.float32).reshape(-1)
    if action.size != ACTION_DIM:
        raise ValueError(
            f"{episode_path}: expected {ACTION_DIM}-D action in step {index}, got {action.shape}"
        )
    return action.astype(np.float32)


def _language_instruction(steps: List[Dict[str, Any]]) -> str:
    for step in steps:
        instruction = step.get("task_description") or step.get("language_instruction")
        if instruction:
            return str(instruction)
    return "teleop task"


def _language_embedding(step: Dict[str, Any]) -> np.ndarray:
    if "language_embedding" in step:
        embedding = np.asarray(step["language_embedding"], dtype=np.float32).reshape(-1)
        if embedding.size == LANGUAGE_EMBEDDING_DIM:
            return embedding
    return np.zeros(LANGUAGE_EMBEDDING_DIM, dtype=np.float32)


def _generate_examples(paths: Iterable[str]) -> Iterator[Tuple[str, Dict[str, Any]]]:
    """Yields RLDS episodes from raw ``episode.npy`` paths."""
    episode_paths = list(paths)
    with tqdm(total=len(episode_paths), desc="Converting RM75 episodes", unit="episode") as progress:
        for episode_path in episode_paths:
            raw_episode = np.load(episode_path, allow_pickle=True)
            steps = [_as_step_dict(step) for step in raw_episode]
            if not steps:
                progress.update(1)
                continue

            instruction = _language_instruction(steps)
            language_embedding = _language_embedding(steps[0])
            episode = []
            for index, step in enumerate(steps):
                image = _image_from_step(step, ("images", "image"))
                if image is None:
                    raise ValueError(f"{episode_path}: missing primary image in step {index}")
                wrist_image = _image_from_step(step, ("wrist_images", "wrist_image"))
                if wrist_image is None:
                    wrist_image = np.zeros_like(image)

                episode.append({
                    "observation": {
                        "image": image,
                        "wrist_image": wrist_image,
                        "state": _state_from_step(step),
                    },
                    "action": _action_from_step(step, episode_path, index),
                    "discount": np.float32(1.0),
                    "reward": np.float32(index == len(steps) - 1),
                    "is_first": index == 0,
                    "is_last": index == len(steps) - 1,
                    "is_terminal": index == len(steps) - 1,
                    "language_instruction": instruction,
                    "language_embedding": language_embedding,
                })

            progress.update(1)
            yield episode_path, {
                "steps": episode,
                "episode_metadata": {
                    "file_path": episode_path,
                },
            }


class Rm75SingleManip(tfds.core.GeneratorBasedBuilder):
    """DatasetBuilder for RM75 single-arm manipulation demonstrations."""

    VERSION = tfds.core.Version("1.0.0")
    RELEASE_NOTES = {
        "1.0.0": "Initial RM75 single-arm manipulation RLDS conversion.",
    }

    def _info(self) -> tfds.core.DatasetInfo:
        return self.dataset_info_from_configs(
            features=tfds.features.FeaturesDict({
                "steps": tfds.features.Dataset({
                    "observation": tfds.features.FeaturesDict({
                        "image": tfds.features.Image(
                            shape=(None, None, 3),
                            dtype=np.uint8,
                            encoding_format="png",
                            doc="Primary RGB camera observation.",
                        ),
                        "wrist_image": tfds.features.Image(
                            shape=(None, None, 3),
                            dtype=np.uint8,
                            encoding_format="png",
                            doc="Wrist RGB camera observation; black image when absent.",
                        ),
                        "state": tfds.features.Tensor(
                            shape=(STATE_DIM,),
                            dtype=np.float32,
                            doc="Robot state: ee_pose xyz+quat, gripper command, 7 joint positions.",
                        ),
                    }),
                    "action": tfds.features.Tensor(
                        shape=(ACTION_DIM,),
                        dtype=np.float32,
                        doc="End-effector delta pose and gripper command: dx dy dz droll dpitch dyaw gripper.",
                    ),
                    "discount": tfds.features.Scalar(dtype=np.float32),
                    "reward": tfds.features.Scalar(dtype=np.float32),
                    "is_first": tfds.features.Scalar(dtype=np.bool_),
                    "is_last": tfds.features.Scalar(dtype=np.bool_),
                    "is_terminal": tfds.features.Scalar(dtype=np.bool_),
                    "language_instruction": tfds.features.Text(),
                    "language_embedding": tfds.features.Tensor(
                        shape=(LANGUAGE_EMBEDDING_DIM,),
                        dtype=np.float32,
                        doc="512-D language embedding placeholder; zeros unless present in source data.",
                    ),
                }),
                "episode_metadata": tfds.features.FeaturesDict({
                    "file_path": tfds.features.Text(doc="Path to the source episode.npy file."),
                }),
            }),
            homepage="https://github.com/realman-robotics",
        )

    def _split_generators(self, dl_manager: tfds.download.DownloadManager):
        del dl_manager
        split_paths = {
            "train": _discover_episode_paths("train"),
            "val": _discover_episode_paths("val"),
        }
        for split_name, paths in split_paths.items():
            print(f"[rm75_single_manip] {split_name}: found {len(paths)} episode.npy files")
        split_paths = {name: paths for name, paths in split_paths.items() if paths}
        if not split_paths:
            raise FileNotFoundError(
                "No RM75 episode.npy files found. Expected files under "
                f"{DATASET_DIR / 'data' / '<split>'}, or set RM75_RLDS_TRAIN_GLOB/RM75_RLDS_VAL_GLOB."
            )
        return {
            name: self._generate_examples(paths)
            for name, paths in split_paths.items()
        }

    def _generate_examples(self, paths: Iterable[str]):
        yield from _generate_examples(paths)
